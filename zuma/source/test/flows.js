// node flows.js : click through the shop and screenshot each state into shots/flow-*.png
const { chromium } = require('playwright');
const U = 'http://127.0.0.1:8772/site3/dist/', out = __dirname + '/shots/flow-';
(async () => { const b = await chromium.launch({ args: ['--proxy-server=' + process.env.HTTPS_PROXY, '--proxy-bypass-list=127.0.0.1;localhost', '--ignore-certificate-errors', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const errs = []; const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } }); const p = await ctx.newPage();
  p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  const shot = async n => { await p.waitForTimeout(900); await p.screenshot({ path: out + n + '.png' }); };
  await p.goto(U + 'shop.html', { waitUntil: 'networkidle' }); await p.waitForTimeout(5000);
  await p.click('#megabtn'); await shot('1-mega');
  await p.keyboard.press('Escape');
  await p.click('#filters [data-f="tissue"]'); await p.evaluate(() => scrollTo(0, 380)); await shot('2-filter-tissue');
  console.log('visible cards after tissue filter:', await p.$$eval('#grid .z-pcard', els => els.filter(e => !e.hidden).map(e => e.dataset.no).join(',')));
  await p.selectOption('#sort', 'high'); await p.click('#filters [data-f="all"]');
  console.log('order high-low:', await p.$$eval('#grid .z-pcard', els => els.map(e => e.dataset.no).join(',')));
  await p.hover('#grid .z-pcard[data-no="04"] .z-pic', { force: true }); await p.waitForTimeout(400);
  await p.click('#grid .z-pcard[data-no="04"] [data-quick]'); await shot('3-quickview');
  await p.click('#d-add'); await p.waitForTimeout(300); await p.click('#drawer [data-close]'); await p.waitForTimeout(500);
  await p.click('#grid .z-pcard[data-no="02"] [data-csize="0"]'); await p.click('#grid .z-pcard[data-no="02"] [data-qadd]'); await shot('4-toast');
  await p.click('#cartbtn'); await shot('5-cart');
  console.log('cart lines:', await p.$$eval('#c-items li .t', els => els.map(e => e.textContent).join(' | ')), 'total', await p.textContent('#c-total'));
  await p.click('#cart [data-close]'); await p.waitForTimeout(500);
  await p.goto(U + 'n02-bpc-157.html?size=0', { waitUntil: 'networkidle' }); await p.waitForTimeout(5000);
  console.log('pdp size from url:', await p.$eval('#d-sizes input:checked', e => e.value), await p.textContent('#d-add'));
  await p.click('#o-standing'); await p.click('#q-plus'); await p.click('#q-plus');
  console.log('pdp after subscribe x3:', await p.textContent('#d-add'), '|', await p.textContent('#pdp-price'), await p.textContent('#pdp-per'));
  await p.click('.pdp-thumb[data-view="label"]'); await shot('6-pdp-label');
  await p.evaluate(() => document.querySelector('#lot-record').scrollIntoView()); await p.waitForTimeout(600);
  await shot('7-buybar');
  await p.click('#lot-record a.z-link'); await p.waitForTimeout(300);
  await p.goto(U + 'index.html#lots', { waitUntil: 'networkidle' }); await p.waitForTimeout(3000);
  await p.click('#lotrows [data-coa="01"]'); await shot('8-coa');
  await p.goto(U + 'shop.html#faq-returns', { waitUntil: 'networkidle' }); await p.waitForTimeout(1500);
  console.log('faq-returns open:', await p.$eval('#faq-returns', e => e.open));
  console.log('errors:', errs.join(' | ') || 'none'); await b.close(); })();
